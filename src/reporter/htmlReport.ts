import type { AiNote, ButtonCheck, CheckStatus, ConsoleIssue, LinkCheck, SmokeResult, StatusCounts } from '../core/index.js';

/**
 * Renders a smoke result as a self-contained HTML page (inline CSS and JS, no external requests).
 *
 * Everything that comes from the tested page (texts, labels, URLs, error messages) is escaped,
 * and only http(s) URLs become clickable, so a hostile page can't inject script into the report.
 */
export function renderHtmlReport(r: SmokeResult): string {
  const v = verdict(r);
  const title = `Smoke report: ${hostOf(r.url)}`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'">
<title>${esc(title)}</title>
<style>${CSS}</style>
</head>
<body>
<main>
  <header>
    <div class="verdict ${v.cls}">${esc(v.text)}</div>
    <h1>Smoke report</h1>
    <p class="url">${linkify(r.url)}</p>
    <dl class="meta">
      <div><dt>Started</dt><dd>${esc(formatDate(r.startedAt))}</dd></div>
      <div><dt>Duration</dt><dd>${esc(formatMs(r.durationMs))}${r.timedOut ? ' <span class="badge not-checked">time budget ran out</span>' : ''}</dd></div>
      <div><dt>Browser</dt><dd>${esc(r.browser)}</dd></div>
    </dl>
  </header>

  ${r.ai ? aiSection(r) : ''}
  ${pageSection(r)}
  ${r.page.ok ? summaryCards(r) : ''}
  ${r.page.ok ? filterBar(r.summary.total) : ''}
  ${r.page.ok ? linksSection(r.links) : ''}
  ${r.page.ok ? buttonsSection(r.buttons) : ''}
  ${riskySection(r.buttons)}
  ${consoleSection(r.consoleIssues)}

  <footer>Generated by smoke-agent · full details in the JSON file next to this report</footer>
</main>
<script>${JS}</script>
</body>
</html>
`;
}

// ---------- sections ----------

function pageSection(r: SmokeResult): string {
  const p = r.page;
  const status = p.ok ? 'pass' : 'fail';
  const rows = [
    ['Result', `${badge(status)} ${p.status !== null ? `HTTP ${p.status}` : esc(p.error ?? 'did not load')}`],
    ['Title', esc(p.title ?? '')],
    ['Load time', esc(formatMs(p.loadTimeMs))],
  ];
  if (p.finalUrl && p.finalUrl !== r.url) rows.push(['Redirected to', linkify(p.finalUrl)]);
  return `<section>
    <h2>Page load</h2>
    <table class="kv">${rows.map(([k, val]) => `<tr><th>${k}</th><td>${val}</td></tr>`).join('')}</table>
  </section>`;
}

function summaryCards(r: SmokeResult): string {
  const onPage = r.links.reduce((n, l) => n + l.occurrences, 0);
  const card = (label: string, sub: string, c: StatusCounts) => `
    <div class="card">
      <div class="card-title">${label}</div>
      <div class="card-total">${c.total}</div>
      <div class="card-sub">${sub}</div>
      <div class="bar">${(['fail', 'warning', 'not-checked', 'skipped', 'pass'] as CheckStatus[])
        .filter((s) => c[s] > 0)
        .map((s) => `<span class="seg ${s}" style="flex:${c[s]}" title="${c[s]} ${s}"></span>`)
        .join('')}</div>
      <div class="counts">${countsText(c)}</div>
    </div>`;
  const consoleCard = `
    <div class="card">
      <div class="card-title">Console errors</div>
      <div class="card-total">${r.consoleIssues.length}</div>
      <div class="card-sub">${r.consoleIssues.filter((i) => !i.duringClickOf).length} during page load</div>
    </div>`;
  return `<section class="cards">
    ${card('Links', `unique URLs (${onPage} on page)`, r.summary.links)}
    ${card('Buttons', 'found on page', r.summary.buttons)}
    ${consoleCard}
  </section>`;
}

function filterBar(total: StatusCounts): string {
  const chips = (['fail', 'warning', 'not-checked', 'skipped', 'pass'] as CheckStatus[])
    .filter((s) => total[s] > 0)
    .map((s) => `<button type="button" class="chip" data-filter="${s}">${statusLabel(s)} (${total[s]})</button>`)
    .join('');
  return `<nav class="filters" aria-label="Filter checks by status">
    <span>Show:</span>
    <button type="button" class="chip active" data-filter="all">All (${total.total})</button>
    ${chips}
  </nav>`;
}

function linksSection(links: LinkCheck[]): string {
  if (links.length === 0) return `<section><h2>Links</h2><p class="empty">No links found on the page.</p></section>`;
  const rows = sortBySeverity(links)
    .map((l) => {
      const texts = l.texts.length ? l.texts.map(esc).join('<br>') : '<span class="muted">(no text)</span>';
      const tags = [
        l.external ? '<span class="tag">external</span>' : '',
        l.kind === 'anchor' ? '<span class="tag">anchor</span>' : '',
        !l.visible ? '<span class="tag">hidden</span>' : '',
      ].join('');
      const http = l.httpStatus !== undefined ? `${l.httpStatus}${l.method ? ` <span class="muted">${l.method}</span>` : ''}` : '';
      return `<tr data-status="${l.status}">
        <td>${badge(l.status)}</td>
        <td class="wrap">${linkify(l.url)} ${tags}</td>
        <td>${texts}</td>
        <td class="num">${l.occurrences}</td>
        <td class="num">${http}</td>
        <td class="num">${l.durationMs !== undefined ? esc(formatMs(l.durationMs)) : ''}</td>
        <td class="wrap">${esc(l.message ?? '')}${aiNote(l.ai)}</td>
      </tr>`;
    })
    .join('');
  return `<section>
    <h2>Links <span class="muted">(${links.length})</span></h2>
    <div class="scroll"><table class="checks">
      <thead><tr><th>Status</th><th>URL</th><th>Text</th><th class="num">Count</th><th class="num">HTTP</th><th class="num">Time</th><th>Details</th></tr></thead>
      <tbody>${rows}</tbody>
    </table></div>
  </section>`;
}

function buttonsSection(buttons: ButtonCheck[]): string {
  if (buttons.length === 0) return `<section><h2>Buttons</h2><p class="empty">No buttons found on the page.</p></section>`;
  const rows = sortBySeverity(buttons)
    .map((b) => {
      const reactions = (b.reactions ?? []).map((x) => `<span class="tag">${esc(x)}</span>`).join('');
      const nav = b.navigatedTo ? `<div class="muted">→ ${linkify(b.navigatedTo.url)}</div>` : '';
      return `<tr data-status="${b.status}">
        <td>${badge(b.status)}</td>
        <td>${esc(b.label)}</td>
        <td><code>${esc(b.selector)}</code></td>
        <td>${reactions}${nav}</td>
        <td class="num">${b.durationMs !== undefined ? esc(formatMs(b.durationMs)) : ''}</td>
        <td class="wrap">${esc(b.message ?? '')}${b.skipReason === 'ai-risky' ? '' : aiNote(b.ai)}</td>
      </tr>`;
    })
    .join('');
  return `<section>
    <h2>Buttons <span class="muted">(${buttons.length})</span></h2>
    <div class="scroll"><table class="checks">
      <thead><tr><th>Status</th><th>Label</th><th>Selector</th><th>Reaction</th><th class="num">Time</th><th>Details</th></tr></thead>
      <tbody>${rows}</tbody>
    </table></div>
  </section>`;
}

function riskySection(buttons: ButtonCheck[]): string {
  const risky = buttons.filter((b) => b.skipReason === 'risky' || b.skipReason === 'ai-risky');
  if (risky.length === 0) return '';
  const items = risky
    .map((b) => {
      const why =
        b.skipReason === 'risky'
          ? `<span class="muted">keyword “${esc(b.matchedKeyword ?? '')}”</span>${aiNote(b.ai)}`
          : `<span class="tag ai">AI review</span> <span class="muted">${esc(b.ai?.reason ?? '')}</span>`;
      return `<li><strong>${esc(b.label)}</strong> <code>${esc(b.selector)}</code> ${why}</li>`;
    })
    .join('');
  return `<section class="callout">
    <h2>Check manually: risky buttons not clicked <span class="muted">(${risky.length})</span></h2>
    <p>These buttons could have side effects (deleting data, logging out, paying…), so they were not clicked.</p>
    <ul>${items}</ul>
  </section>`;
}

function consoleSection(issues: ConsoleIssue[]): string {
  if (issues.length === 0) return '';
  const rows = issues
    .map((i) => `<tr>
      <td><span class="tag">${i.type === 'page-error' ? 'uncaught error' : 'console.error'}</span></td>
      <td>${i.duringClickOf ? `click on “${esc(i.duringClickOf)}”` : 'page load'}</td>
      <td class="wrap"><code>${esc(i.message)}</code></td>
    </tr>`)
    .join('');
  return `<section>
    <h2>Console errors <span class="muted">(${issues.length})</span></h2>
    <div class="scroll"><table class="checks">
      <thead><tr><th>Type</th><th>When</th><th>Message</th></tr></thead>
      <tbody>${rows}</tbody>
    </table></div>
  </section>`;
}

function aiSection(r: SmokeResult): string {
  const ai = r.ai!;
  const parts: string[] = [];
  if (ai.summary) parts.push(ai.summary.split(/\n+/).map((p) => `<p>${esc(p)}</p>`).join(''));
  if (ai.recommendations?.length) {
    parts.push(`<h3>Next steps</h3><ul>${ai.recommendations.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`);
  }
  const status: string[] = [];
  if (ai.buttonReview) {
    const br = ai.buttonReview;
    status.push(
      br.ok
        ? `Reviewed ${br.reviewed} button(s) before clicking; ${br.addedSkips} extra skipped as risky (${esc(formatMs(br.durationMs))}).`
        : `Button review failed: ${esc(br.error ?? 'unknown error')}`,
    );
  }
  if (ai.triage) {
    status.push(
      ai.triage.ok
        ? `Triage and summary took ${esc(formatMs(ai.triage.durationMs))}.`
        : `Triage and summary failed: ${esc(ai.triage.error ?? 'unknown error')}`,
    );
  }
  return `<section class="ai-panel">
    <h2>AI review <span class="muted">${ai.model ? `(${esc(ai.model)})` : ''}</span></h2>
    ${parts.join('') || '<p class="muted">No AI summary available.</p>'}
    <p class="ai-meta">${status.join(' ')} AI output is advisory and may be wrong; it never changes a check's status or the exit code.</p>
  </section>`;
}

/** An inline AI opinion under a check's details. */
function aiNote(note?: AiNote): string {
  if (!note) return '';
  const cls = note.verdict === 'likely-bug' || note.verdict === 'risky' ? 'fail' : note.verdict === 'unsure' ? 'not-checked' : 'pass';
  return `<div class="ai-note"><span class="tag ai">AI</span><span class="badge ${cls}">${esc(note.verdict)}</span> ${esc(note.reason)}</div>`;
}

// ---------- helpers ----------

const SEVERITY: Record<CheckStatus, number> = { fail: 0, warning: 1, 'not-checked': 2, skipped: 3, pass: 4 };

function sortBySeverity<T extends { status: CheckStatus }>(items: T[]): T[] {
  return [...items].sort((a, b) => SEVERITY[a.status] - SEVERITY[b.status]);
}

function verdict(r: SmokeResult): { text: string; cls: string } {
  if (!r.page.ok) return { text: 'ERROR: page did not load', cls: 'fail' };
  const { fail, warning } = r.summary.total;
  if (fail > 0) return { text: `FAIL: ${fail} failed check${fail === 1 ? '' : 's'}`, cls: 'fail' };
  if (warning > 0) return { text: `PASS with ${warning} warning${warning === 1 ? '' : 's'}`, cls: 'warning' };
  return { text: 'PASS', cls: 'pass' };
}

function statusLabel(s: CheckStatus): string {
  return { pass: 'Pass', warning: 'Warning', fail: 'Fail', skipped: 'Skipped', 'not-checked': 'Not checked' }[s];
}

function badge(s: CheckStatus): string {
  return `<span class="badge ${s}">${statusLabel(s)}</span>`;
}

function countsText(c: StatusCounts): string {
  return (['pass', 'warning', 'fail', 'skipped', 'not-checked'] as CheckStatus[])
    .filter((s) => c[s] > 0 || s === 'fail')
    .map((s) => `<span class="dot ${s}"></span>${c[s]} ${statusLabel(s).toLowerCase()}`)
    .join(' ');
}

/** Clickable only for http(s); anything else (javascript:, data:, …) is shown as plain text. */
function linkify(url: string): string {
  if (/^https?:\/\//i.test(url)) return `<a href="${esc(url)}" target="_blank" rel="noopener noreferrer">${esc(url)}</a>`;
  return `<span>${esc(url)}</span>`;
}

function esc(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

function hostOf(url: string): string {
  try {
    return new URL(url).host;
  } catch {
    return url;
  }
}

function formatMs(ms: number): string {
  return ms < 1000 ? `${ms} ms` : `${(ms / 1000).toFixed(1)} s`;
}

function formatDate(iso: string): string {
  const d = new Date(iso);
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`;
}

