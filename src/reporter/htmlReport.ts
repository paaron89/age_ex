const JS = `
document.querySelectorAll('.chip').forEach(function (chip) {
  chip.addEventListener('click', function () {
    var f = chip.getAttribute('data-filter');
    document.querySelectorAll('.chip').forEach(function (c) { c.classList.toggle('active', c === chip); });
    document.querySelectorAll('tr[data-status]').forEach(function (row) {
      row.classList.toggle('hidden', f !== 'all' && row.getAttribute('data-status') !== f);
    });
  });
});
`;
